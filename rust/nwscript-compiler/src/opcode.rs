#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum Opcode {
    Assignment = 0x01,
    RunstackAdd = 0x02,
    RunstackCopy = 0x03,
    Constant = 0x04,
    ExecuteCommand = 0x05,
    LogicalAnd = 0x06,
    LogicalOr = 0x07,
    InclusiveOr = 0x08,
    ExclusiveOr = 0x09,
    BooleanAnd = 0x0a,
    Equal = 0x0b,
    NotEqual = 0x0c,
    GEQ = 0x0d,
    GT = 0x0e,
    LT = 0x0f,
    LEQ = 0x10,
    ShiftLeft = 0x11,
    ShiftRight = 0x12,
    UShiftRight = 0x13,
    Add = 0x14,
    Sub = 0x15,
    Mul = 0x16,
    Div = 0x17,
    Modulus = 0x18,
    Negation = 0x19,
    OnesComplement = 0x1a,
    ModifyStackPointer = 0x1b,
    StoreIp = 0x1c,
    Jmp = 0x1d,
    Jsr = 0x1e,
    Jz = 0x1f,
    Ret = 0x20,
    DeStruct = 0x21,
    BooleanNot = 0x22,
    Decrement = 0x23,
    Increment = 0x24,
    Jnz = 0x25,
    AssignmentBase = 0x26,
    RunstackCopyBase = 0x27,
    DecrementBase = 0x28,
    IncrementBase = 0x29,
    SaveBasePointer = 0x2a,
    RestoreBasePointer = 0x2b,
    StoreState = 0x2c,
    NoOperation = 0x2d,
}

